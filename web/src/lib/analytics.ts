/**
 * 구글 애널리틱스 스위치.
 *
 * ── 왜 환경변수 하나로 묶는가 ──
 *
 * 분석 도구를 붙이는 일은 코드 한 줄로 끝나지 않는다. 최소한 세 곳이
 * 같이 움직여야 한다.
 *
 *   1. 스크립트 삽입          (components/analytics.tsx)
 *   2. CSP 에 구글 도메인 허용 (next.config.ts)
 *   3. 쿠키 정책 · 개인정보처리방침 고지 (app/cookies, app/privacy)
 *
 * 사람이 셋을 다 기억하는 방식은 반드시 어긋난다. 특히 3번이 늦으면
 * «고지 없이 수집한 기간» 이 생기고, 그건 나중에 문서를 고쳐도
 * 되돌릴 수 없다. 그래서 셋 다 이 값 하나를 읽게 했다.
 *
 * 값이 없으면 아무 일도 일어나지 않는다 — 스크립트도, CSP 완화도,
 * 「분석 도구를 씁니다」 라는 문구도 없다. 지금이 그 상태다.
 *
 * ── 켜는 방법 ──
 *
 *   web/.env.local (또는 배포 환경변수) 에
 *     NEXT_PUBLIC_GA_ID=G-XXXXXXXXXX
 *   를 넣고 다시 빌드한다. CSP 와 고지 문구가 같이 따라온다.
 *
 * ★ NEXT_PUBLIC_ 접두사는 «브라우저에 노출된다» 는 뜻이다.
 *   측정 ID 는 원래 페이지 소스에 그대로 실리는 공개 값이라 괜찮다.
 *   비밀 키를 이 접두사로 두면 안 된다.
 */

const raw = process.env.NEXT_PUBLIC_GA_ID?.trim() ?? "";

/**
 * 형식이 맞을 때만 인정한다.
 *
 * 오타나 따옴표가 섞인 값이 들어오면 스크립트는 조용히 실패하는데,
 * CSP 만 열리고 고지 문구만 붙는 최악의 조합이 된다 —
 * 「수집한다고 써 놓고 실제로는 수집 안 하는」 상태다.
 * 형식 검사로 그 조합을 막는다.
 */
export const GA_ID = /^G-[A-Z0-9]{6,}$/.test(raw) ? raw : "";

/** 분석 도구가 켜져 있는가. 화면·CSP·법적 문서가 모두 이 값을 본다. */
export const ANALYTICS_ENABLED = GA_ID !== "";
